def canonical_spot(spot):
    value = spot.casefold()
    if value.startswith("bright spot"):
        return "Bright Spot"
    if value == "gray spot":
        return "Gray Spot"
    if value == "blind spot":
        return "Blind Spot"
    return None


def build_category_tree_data(records, category):
    """Group one test category by training status, match status, and Spot."""
    tree = {}
    total = 0
    for record in records:
        if record["category"] != category:
            continue
        spot = canonical_spot(record["spot"])
        if spot is None:
            continue
        levels = tree.setdefault(record["training"], {}).setdefault(record["match"], {})
        levels[spot] = levels.get(spot, 0) + 1
        total += 1
    return tree, total


def load_fonts():
    for font_path in (
        "/System/Library/Fonts/Supplemental/Arial.ttf",
        "/Library/Fonts/Arial.ttf",
    ):
        if os.path.exists(font_path):
            try:
                return (ImageFont.truetype(font_path, 14),
                        ImageFont.truetype(font_path, 12),
                        ImageFont.truetype(font_path, 18))
            except OSError:
                pass
    default = ImageFont.load_default()
    return default, default, default


