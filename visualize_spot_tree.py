def norm(value):
    return "" if value is None else str(value).strip()


def header_key(value):
    return re.sub(r"\s+", " ", norm(value)).casefold()


def safe_name(value):
    value = re.sub(r"[^A-Za-z0-9_-]+", "_", value.strip()).strip("_")
    return value or "spot"


def load_evaluation_data(path):
    """Read either evaluator output or the compact X1-X4/Y decision-log format."""
    workbook = load_workbook(path, read_only=True, data_only=True)
    trained_categories = set()
    if "Category Analysis" in workbook.sheetnames:
        sheet = workbook["Category Analysis"]
        rows = sheet.iter_rows(values_only=True)
        headers = next(rows, ())
        if headers and norm(headers[0]).lower() == "category":
            trained_categories = {
                norm(row[0]) for row in rows if row and norm(row[0])
            }

    # The compact meta-decision workbook uses these headers and may name its
    # sheet arbitrarily. The traditional evaluator workbook uses Predictions.
    layouts = (
        {
            "category": "test category",
            "spot": "y spot",
            "training": "y trained status",
            "match": "y match status",
        },
        {
            "category": "folder label",
            "spot": "spot",
            "status": "status",
            "consensus": "consensus label",
        },
    )
    selected = None
    observed = []
    for sheet in workbook.worksheets:
        # Look at the first few rows so a title row above the column headers is OK.
        for row_number, row in enumerate(sheet.iter_rows(min_row=1, max_row=20, values_only=True), start=1):
            keys = [header_key(value) for value in row]
            observed.append("{} row {}: {}".format(sheet.title, row_number, [v for v in keys if v]))
            for layout in layouts:
                if all(header in keys for header in layout.values()):
                    positions = {field: keys.index(header) for field, header in layout.items()}
                    selected = (sheet, row_number, positions, layout)
                    break
            if selected:
                break
        if selected:
            break
    if not selected:
        workbook.close()
        raise ValueError(
            "Could not find supported evaluation columns. Expected either "
            "'Test category', 'Y Trained status', 'Y Match status', 'Y Spot' "
            "or the standard 'Folder label', 'Status', 'Spot', 'Consensus label'. "
            "Sheets inspected: {}".format("; ".join(observed))
        )

    sheet, header_row, positions, layout = selected

    records = []
    for row in sheet.iter_rows(min_row=header_row + 1, values_only=True):
        if not row:
            continue
        category = norm(row[positions["category"]]) or "Uncategorized"
        spot = norm(row[positions["spot"]])
        if not category or not spot:
            continue
        if "status" in positions and norm(row[positions["status"]]).upper() != "OK":
            continue
        if "training" in positions:
            training = norm(row[positions["training"]]).title()
            if training not in ("Trained", "Untrained"):
                continue
        else:
            training = "Trained" if category in trained_categories else "Untrained"
        if "match" in positions:
            match = norm(row[positions["match"]]).title()
            if match not in ("Matched", "Unmatched"):
                continue
        else:
            consensus = norm(row[positions["consensus"]])
            match = "Matched" if consensus == category else "Unmatched"
        records.append({
            "category": category,
            "spot": spot,
            "training": training,
            "match": match,
        })
    workbook.close()
    if "training" not in positions and not trained_categories:
        raise ValueError(
            "No trained categories were found in 'Category Analysis'. "
            "The workbook must be generated by evaluate_image_folder.py or its additional-categories version."
        )
    return records, trained_categories


def select_spot(records, spot):
    if spot == "Bright Spot":
        return [record for record in records if record["spot"].startswith("Bright Spot")]
    return [record for record in records if record["spot"] == spot]


def build_tree_data(records, spot):
    filtered = select_spot(records, spot)
    tree = {}
    for record in filtered:
        tree.setdefault(record["training"], {}).setdefault(record["match"], {})
        categories = tree[record["training"]][record["match"]]
        categories[record["category"]] = categories.get(record["category"], 0) + 1
    return tree, len(filtered)


def build_blind_training_tree(records):
    """Merge match outcomes and count Blind Spot samples by training status/category."""
    tree = {}
    total = 0
    for record in records:
        if record["spot"] != "Blind Spot":
            continue
        categories = tree.setdefault(record["training"], {})
        category = record["category"]
        categories[category] = categories.get(category, 0) + 1
        total += 1
    return tree, total


def build_spot_training_tree(records, spot):
    """Aggregate Match status and group selected Spot by training/category."""
    tree = {}
    filtered = select_spot(records, spot)
    for record in filtered:
        categories = tree.setdefault(record["training"], {})
        category = record["category"]
        categories[category] = categories.get(category, 0) + 1
    return tree, len(filtered)


