        self.current_images[view_name] = ImageTk.PhotoImage(image)
        canvas.delete("all")
        canvas.create_image(0, 0, anchor="nw", image=self.current_images[view_name])
        canvas.configure(scrollregion=(0, 0, image.width, image.height))
        status_label.configure(text="{} samples  |  Diagram: {}  |  Excel: {}".format(
            total, os.path.basename(png_path), os.path.basename(excel_path)))

