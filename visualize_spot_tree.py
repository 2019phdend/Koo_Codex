def draw_bright_summary_image(tree, total):
    """Draw Bright tier totals without expanding the test-category leaves."""
    leaves = []
    for tier in ("Prime", "High", "Normal", "Low 1", "Low 2"):
        for training in TRAINING_ORDER:
            for match in MATCH_ORDER:
                count = sum(tree.get(tier, {}).get(training, {}).get(match, {}).values())
                if count:
                    leaves.append((tier, training, match, count))

    row_gap = 42
    width = 900
    height = max(390, 140 + row_gap * max(1, len(leaves)))
    image = Image.new("RGB", (width, height), "#F6F8FB")
    draw = ImageDraw.Draw(image)
    font, small_font, title_font = load_fonts()
    root_bg, root_fg = SPOT_COLORS["Bright Spot"]
    draw.text((20, 18), "BRIGHT SPOT TIERS  |  {} samples".format(total),
              fill=root_fg, font=title_font)
    draw.text((20, 52), "Test category omitted; counts are grouped by tier, training, and match status",
              fill="#526174", font=small_font)
    for x, label in ((20, "BRIGHT"), (205, "TIER"), (440, "TRAINED STATUS"), (660, "MATCH")):
        draw.text((x, 95), label, fill="#526174", font=small_font)

    if not leaves:
        draw.rounded_rectangle((20, 180, 165, 222), radius=9, fill=root_bg, outline=root_fg, width=2)
        draw.text((29, 193), "Bright Spot (0)", fill=root_fg, font=font)
        draw.text((210, 193), "No Bright Spot samples", fill="#526174", font=font)
        return image

    y_for_leaf = {leaf: 125 + index * row_gap for index, leaf in enumerate(leaves)}
    tier_centers, training_centers = {}, {}
    for tier, training, match, count in leaves:
        y = y_for_leaf[(tier, training, match, count)]
        tier_centers.setdefault(tier, []).append(y)
        training_centers.setdefault((tier, training), []).append(y)
    tier_centers = {key: sum(values) / float(len(values)) for key, values in tier_centers.items()}
    training_centers = {key: sum(values) / float(len(values)) for key, values in training_centers.items()}
    root_y = sum(y_for_leaf.values()) / float(len(y_for_leaf))
    root_box = (20, root_y - 21, 165, root_y + 21)
    draw.rounded_rectangle(root_box, radius=9, fill=root_bg, outline=root_fg, width=2)
    draw.text((root_box[0] + 9, root_box[1] + 12), "Bright Spot ({})".format(total),
              fill=root_fg, font=font)

    def node(box, center_y, label, count, fill="#FFFFFF", outline="#9AA8B8", color="#263E5B"):
        x1, x2 = box
        y1, y2 = center_y - 18, center_y + 18
        draw.rounded_rectangle((x1, y1, x2, y2), radius=8, fill=fill, outline=outline, width=1)
        draw.text((x1 + 8, y1 + 10), "{} ({})".format(label, count), fill=color, font=small_font)

    for tier, center_y in tier_centers.items():
        count = sum(
            sum(values.values())
            for training_data in tree[tier].values()
            for values in training_data.values()
        )
        node((205, 390), center_y, tier, count, "#E8F6EF", "#4C9B76")
        draw.line([(root_box[2], root_y), (185, root_y), (185, center_y), (205, center_y)],
                  fill="#A9B4C2", width=2)

    for (tier, training), center_y in training_centers.items():
        count = sum(sum(categories.values()) for categories in tree[tier][training].values())
        node((440, 620), center_y, training, count, "#EAF0FA", "#7793B7")
        parent_y = tier_centers[tier]
        draw.line([(390, parent_y), (420, parent_y), (420, center_y), (440, center_y)],
                  fill="#A9B4C2", width=2)

    for tier, training, match, count in leaves:
        center_y = y_for_leaf[(tier, training, match, count)]
        parent_y = training_centers[(tier, training)]
        draw.line([(620, parent_y), (645, parent_y), (645, center_y), (660, center_y)],
                  fill="#A9B4C2", width=2)
        node((660, 875), center_y, match, count)
    return image


