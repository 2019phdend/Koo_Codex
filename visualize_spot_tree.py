def main():
    root = tk.Tk()
    root.withdraw()
    root.attributes("-topmost", True)
    source_path = filedialog.askopenfilename(
        title="Select an image evaluation Excel file",
        filetypes=[("Excel workbooks", "*.xlsx"), ("All files", "*.*")],
    )
    root.destroy()
    if not source_path:
        return
    try:
        records, _trained_categories = load_evaluation_data(source_path)
    except Exception as exc:
        error_root = tk.Tk()
        error_root.withdraw()
        messagebox.showerror("Could not read evaluation workbook", str(exc), parent=error_root)
        error_root.destroy()
        return

    app_root = tk.Tk()
    SpotTreeApp(app_root, source_path, records)
    app_root.mainloop()


if __name__ == "__main__":
    main()
