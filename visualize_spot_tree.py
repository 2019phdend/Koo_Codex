def save_tree_excel(path, root_label, tree, total, terminal_header="Test category"):
    workbook = Workbook()
    sheet = workbook.active
    is_spot_root = terminal_header.casefold() == "test category"
    sheet.title = "Spot Tree" if is_spot_root else "Category Tree"
    sheet.append(["Selected Spot" if is_spot_root else "Test category", root_label])
    sheet.append(["Total samples", total])
    sheet.append([])
    sheet.append(["Training status", "Prediction match", terminal_header, "Sample count"])
    for training in TRAINING_ORDER:
        for match in MATCH_ORDER:
            terminals = tree.get(training, {}).get(match, {})
            if not terminals:
                continue
            sheet.append([training, match, "Subtotal", sum(terminals.values())])
            if terminal_header.casefold() == "spot":
                terminal_items = [(key, terminals[key]) for key in SPOT_TERMINAL_ORDER if key in terminals]
            else:
                terminal_items = sorted(terminals.items(), key=lambda item: item[0].casefold())
            for terminal, count in terminal_items:
                sheet.append([training, match, terminal, count])
    sheet.freeze_panes = "A5"
    sheet.auto_filter.ref = "A4:D{}".format(max(4, sheet.max_row))
    for cell in sheet[4]:
        cell.font = Font(name="Arial", bold=True, color="FFFFFF")
        cell.fill = PatternFill(fill_type="solid", fgColor="315C7D")
    for column, width in (("A", 20), ("B", 22), ("C", 34), ("D", 17)):
        sheet.column_dimensions[column].width = width
    workbook.save(path)


