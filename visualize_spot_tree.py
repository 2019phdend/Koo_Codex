def build_bright_tier_tree_data(records, tier):
    """Build the training/match/category tree for one Bright Spot tier."""
    filtered = [record for record in records if record["spot"] == tier]
    tree = {}
    for record in filtered:
        categories = tree.setdefault(record["training"], {}).setdefault(record["match"], {})
