    draw.rounded_rectangle(root_box, radius=9, fill=root_bg, outline=root_fg, width=2)
    draw.text((root_box[0] + 10, root_box[1] + 12), "Bright Spot ({})".format(total),
              fill=root_fg, font=font)

    def branch(box, center_y, text, count, fill="#FFFFFF", outline="#9AA8B8", text_color="#263E5B"):
        x1, x2 = box
        y1, y2 = center_y - 17, center_y + 17
        draw.rounded_rectangle((x1, y1, x2, y2), radius=8, fill=fill, outline=outline, width=1)
        draw.text((x1 + 7, y1 + 9), "{} ({})".format(text, count), fill=text_color, font=small_font)

    tier_counts = {tier: sum(sum(cats.values()) for matches in tree[tier].values() for cats in matches.values())
                   for tier in tree}
    for tier, center_y in tier_centers.items():
        branch((185, 350), center_y, tier, tier_counts[tier], "#E8F6EF", "#4C9B76")
        draw.line([(root_box[2], root_y), (175, root_y), (175, center_y), (185, center_y)],
                  fill="#A9B4C2", width=2)

    for (tier, training), center_y in training_centers.items():
        count = sum(sum(cats.values()) for cats in tree[tier][training].values())
        branch((390, 555), center_y, training, count, "#EAF0FA", "#7793B7")
        tier_y = tier_centers[tier]
        draw.line([(350, tier_y), (370, tier_y), (370, center_y), (390, center_y)],
                  fill="#A9B4C2", width=2)

    for (tier, training, match), center_y in match_centers.items():
        count = sum(tree[tier][training][match].values())
        branch((590, 750), center_y, match, count)
        parent_y = training_centers[(tier, training)]
        draw.line([(555, parent_y), (575, parent_y), (575, center_y), (590, center_y)],
                  fill="#A9B4C2", width=2)

    for tier, training, match, category, count in leaves:
        center_y = y_for_leaf[(tier, training, match, category, count)]
        x1, x2 = 785, 1105
        draw.line([(750, match_centers[(tier, training, match)]), (770, match_centers[(tier, training, match)]),
                   (770, center_y), (x1, center_y)], fill="#A9B4C2", width=2)
        draw.rounded_rectangle((x1, center_y - 17, x2, center_y + 17), radius=8,
                               fill="#FFFFFF", outline="#CBD3DD", width=1)
        label = category
        while draw.textbbox((0, 0), label, font=small_font)[2] > 250 and len(label) > 5:
            label = label[:-4] + "..."
        draw.text((x1 + 7, center_y - 8), "{} ({})".format(label, count),
                  fill="#263E5B", font=small_font)
    return image


